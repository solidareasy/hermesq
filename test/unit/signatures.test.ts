import { GITHUB_VECTOR, SLACK_VECTOR, STRIPE_VECTOR } from '../fixtures/providers';

const h = (o: Record<string, string>) => new Headers(o);

describe('GitHub X-Hub-Signature-256 (published test vector)', () => {
  const input = (sig?: string) => ({ headers: h(sig ? { 'x-hub-signature-256': sig } : {}), raw: GITHUB_VECTOR.body, secret: GITHUB_VECTOR.secret, now: 0 });
  it('accepts the documented signature', async () => {
    expect(await github.verify(input(GITHUB_VECTOR.signature), undefined)).toEqual({ ok: true });
  });
  it('rejects a one-character change in the body', async () => {
    expect(await github.verify({ ...input(GITHUB_VECTOR.signature), raw: 'Hello, World?' }, undefined)).toEqual({ ok: false, reason: 'bad_signature' });
  });
  it('rejects the wrong secret and a missing header', async () => {
    expect(await github.verify({ ...input(GITHUB_VECTOR.signature), secret: 'other' }, undefined)).toEqual({ ok: false, reason: 'bad_signature' });
    expect(await github.verify(input(), undefined)).toEqual({ ok: false, reason: 'missing_signature' });
  });
});

describe('Slack v0 signature (published worked example)', () => {
  const now = Number(SLACK_VECTOR.timestamp);
  const input = (o: Partial<{ sig: string; ts: string; now: number; raw: string }> = {}) => ({
    headers: h({ 'x-slack-signature': o.sig ?? SLACK_VECTOR.signature, 'x-slack-request-timestamp': o.ts ?? SLACK_VECTOR.timestamp }),
    raw: o.raw ?? SLACK_VECTOR.body,
    secret: SLACK_VECTOR.secret,
    now: o.now ?? now,
  });
  it('accepts the documented signature', async () => {
    expect(await slack.verify(input(), undefined)).toEqual({ ok: true });
  });
  it('rejects a replay older than 5 minutes even with a valid signature', async () => {
    expect(await slack.verify(input({ now: now + 301 }), undefined)).toEqual({ ok: false, reason: 'stale_timestamp' });
    expect(await slack.verify(input({ now: now + 299 }), undefined)).toEqual({ ok: true });
  });
  it('rejects a tampered timestamp (it is part of the signed string)', async () => {
    expect(await slack.verify(input({ ts: String(now + 1), now }), undefined)).toEqual({ ok: false, reason: 'bad_signature' });
  });
});

describe('Stripe-Signature (generated by the official stripe SDK)', () => {
  const input = (o: Partial<{ header: string; now: number; raw: string; secret: string }> = {}) => ({
    headers: h({ 'stripe-signature': o.header ?? STRIPE_VECTOR.header }),
    raw: o.raw ?? STRIPE_VECTOR.body,
    secret: o.secret ?? STRIPE_VECTOR.secret,
    now: o.now ?? STRIPE_VECTOR.timestamp,
  });
  it('accepts the SDK-generated header', async () => {
    expect(await stripe.verify(input(), undefined)).toEqual({ ok: true });
  });
  it('accepts when one of several v1 signatures matches (secret rotation)', async () => {
    const [t, v1] = STRIPE_VECTOR.header.split(',');
    expect(await stripe.verify(input({ header: `${t},v1=${'0'.repeat(64)},${v1}` }), undefined)).toEqual({ ok: true });
  });
  it('rejects stale timestamps, tampered bodies and malformed headers', async () => {
    expect(await stripe.verify(input({ now: STRIPE_VECTOR.timestamp + 301 }), undefined)).toEqual({ ok: false, reason: 'stale_timestamp' });
    expect(await stripe.verify(input({ raw: STRIPE_VECTOR.body.replace('4200', '4201') }), undefined)).toEqual({ ok: false, reason: 'bad_signature' });
    expect(await stripe.verify(input({ header: 'v1=abc' }), undefined)).toEqual({ ok: false, reason: 'malformed_signature' });
  });
  it('uses the event id as delivery id and the type as event type', () => {
    const p = JSON.parse(STRIPE_VECTOR.body);
    expect(stripe.deliveryId(h({}), p)).toBe('evt_1QfixtureWebhookTransfer');
    expect(stripe.eventTypes(h({}), p)).toEqual(['invoice.payment_succeeded']);
  });
});

describe('Linear-Signature', () => {
  const secret = 'lin_wh_test_secret';
  async function input(payload: Record<string, unknown>, now: number, sigOverride?: string) {
    const raw = JSON.stringify(payload);
    return { args: { headers: h({ 'linear-signature': sigOverride ?? (await hmacSha256Hex(secret, raw)) }), raw, secret, now }, payload };
  }
  it('accepts a fresh, correctly signed body', async () => {
    const { args, payload } = await input({ type: 'Issue', action: 'create', webhookTimestamp: 1_700_000_000_000 }, 1_700_000_010);
    expect(await linear.verify(args, payload)).toEqual({ ok: true });
  });
  it('rejects webhookTimestamp outside the 5-minute window', async () => {
    const { args, payload } = await input({ type: 'Issue', webhookTimestamp: 1_700_000_000_000 }, 1_700_000_000 + 301);
    expect(await linear.verify(args, payload)).toEqual({ ok: false, reason: 'stale_timestamp' });
  });
  it('rejects a bad signature before looking at the timestamp', async () => {
    const { args, payload } = await input({ type: 'Issue', webhookTimestamp: 1_700_000_000_000 }, 1_700_000_000, 'ab'.repeat(32));
    expect(await linear.verify(args, payload)).toEqual({ ok: false, reason: 'bad_signature' });
  });
  it('derives Issue.assigned when assigneeId changed', () => {
    const p = { type: 'Issue', action: 'update', updatedFrom: { assigneeId: null } };
    expect(linear.eventTypes(h({}), p)).toEqual(['Issue', 'Issue.update', 'Issue.updated', 'Issue.assigned']);
    expect(linear.eventTypes(h({}), { type: 'Issue', action: 'update', updatedFrom: { title: 'x' } })).not.toContain('Issue.assigned');
  });
});

describe('timingSafeEqual', () => {
  it('compares by value and length', () => {
    expect(timingSafeEqual('abc', 'abc')).toBe(true);
    expect(timingSafeEqual('abc', 'abd')).toBe(false);
    expect(timingSafeEqual('abc', 'abcd')).toBe(false);
  });
});
